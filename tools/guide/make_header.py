# Packs the pictures in assets/guide/*.jpg into src/guide_data.h, so they're inside CIMABox.exe.
# Run after changing a picture:  python tools/guide/make_header.py
import os
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.normpath(os.path.join(here, '..', '..'))
names = ['eleven-1', 'eleven-2', 'eleven-3', 'deepl-1', 'gemini-1', 'claude-1']  # order = GuidePicture in app.h
out = ['// The "how do I get this key?" pictures (generated by tools/guide/make_header.py from assets/guide).',
       '#pragma once', '#include <cstddef>', '#include <cstdint>', '']
for i, n in enumerate(names):
    data = open(os.path.join(root, 'assets', 'guide', n + '.jpg'), 'rb').read()
    out.append('static const uint8_t kGuidePic%d[] = {' % i)
    for k in range(0, len(data), 24):
        out.append('    ' + ','.join(str(b) for b in data[k:k + 24]) + ',')
    out.append('};')
out.append('struct GuidePicData { const uint8_t* jpg; size_t size; };')
out.append('static const GuidePicData kGuidePics[] = {' + ', '.join('{kGuidePic%d, sizeof(kGuidePic%d)}' % (i, i) for i in range(len(names))) + '};')
open(os.path.join(root, 'src', 'guide_data.h'), 'w', newline='\n').write('\n'.join(out) + '\n')
print('wrote src/guide_data.h')

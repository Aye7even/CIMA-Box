import json, re, os, sys
D=os.path.dirname(os.path.abspath(__file__)) + os.sep
en=json.load(open(D+'strings.json'))
LANGS=[('es','Español'),('pt-BR','Português (Brasil)'),('fr','Français'),('de','Deutsch'),('it','Italiano'),
       ('id','Bahasa Indonesia'),('ru','Русский'),('ar','العربية'),('ja','日本語'),('ko','한국어'),('zh-Hans','简体中文')]
def conv(s):
    # %1..%9 are positional (sentence chips): any order, each exactly once
    pos=sorted(re.findall(r'%([1-9])(?![0-9.]*[dsfxiuc])', s))
    s=re.sub(r'%[1-9](?![0-9.]*[dsfxiuc])', '', s)
    out=''.join('#'+p for p in pos); i=0
    while i<len(s):
        if s[i]=='%':
            i+=1
            if i<len(s) and s[i]=='%': i+=1; continue
            while i<len(s) and s[i] in '-+ #0123456789.*hlLzjt': i+=1
            if i<len(s): out+=s[i]
        i+=1
    return out
tables={}; ok=True
for code,name in LANGS:
    f=D+code+'.json'
    if not os.path.exists(f): print(code,'missing file'); tables[code]=['']*len(en); continue
    rows=json.load(open(f, encoding='utf-8'))
    t=[rows.get(e,'') for e in en]
    miss=[en[i] for i in range(len(en)) if not t[i]]
    extra=[k for k in rows if k not in en]
    bad=[i for i in range(len(en)) if t[i] and conv(t[i])!=conv(en[i])]
    if miss or extra or bad: ok=False
    print(f'{code}: {len(en)-len(miss)}/{len(en)}', 'missing', miss[:10] if miss else '', 'extra', extra or '', 'bad %', [(i,en[i],t[i]) for i in bad] or '')
    tables[code]=t
def c(s): return '"'+s.replace('\\','\\\\').replace('"','\\"').replace('\n','\\n')+'"'
out=['// Generated by i18n/build.py from the translation tables. Edit those, not this file.','#pragma once','',
     'struct BuiltInLanguage { const char* code; const char* name; };',
     'static const BuiltInLanguage kBuiltIn[] = {'+', '.join('{%s, %s}'%(c(a),c(b)) for a,b in LANGS)+'};','',
     'static const char* const kStrings[][%d] = {'%(len(LANGS)+1)]
for i,s in enumerate(en):
    out.append('    {'+', '.join([c(s)]+[c(tables[code][i]) for code,_ in LANGS])+'},')
out.append('};')
open(os.path.join(D, '..', '..', 'src', 'i18n_data.h'),'w',encoding='utf-8').write('\n'.join(out)+'\n')
# template for new languages, and the built-in ones as editable files
os.makedirs(os.path.join(D, '..', '..', 'lang'), exist_ok=True)
json.dump({'code':'xx','name':'Your language, in your language','strings':{s:'' for s in en}}, open(os.path.join(D, '..', '..', 'lang', '_template.json.txt'),'w',encoding='utf-8'), ensure_ascii=False, indent=1)
print('OK' if ok else 'PROBLEMS')
